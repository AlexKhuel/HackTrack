'use strict';

const path = require('path');
require('dotenv').config({ path: path.resolve(__dirname, '../../.env') });
const { Pool } = require('pg');

const connectionString = process.env.SUPABASE_DB_URL;
if (!connectionString) {
  throw new Error('Missing SUPABASE_DB_URL in environment');
}

const hasLocalHost = /(?:localhost|127\.0\.0\.1)/i.test(connectionString);
const pool = new Pool({
  connectionString,
  ssl: hasLocalHost ? undefined : { rejectUnauthorized: false },
});

pool.on('error', (err) => {
  // Avoid silent process-level crashes on idle client socket failures.
  console.error('[db] Unexpected PostgreSQL idle client error:', err);
});

let schemaBootstrapPromise = null;

async function ensureAppSchema() {
  if (schemaBootstrapPromise) return schemaBootstrapPromise;

  schemaBootstrapPromise = (async () => {
    await pool.query(`
      CREATE TABLE IF NOT EXISTS app_users (
        id BIGSERIAL PRIMARY KEY,
        google_sub TEXT NOT NULL UNIQUE,
        email TEXT,
        name TEXT,
        picture_url TEXT,
        profile_row_id BIGINT NULL,
        last_login_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
    `);

    await pool.query(`
      ALTER TABLE app_users
      ADD COLUMN IF NOT EXISTS profile_row_id BIGINT NULL;
    `);

    await pool.query(`
      CREATE TABLE IF NOT EXISTS public."user" (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
        name TEXT NULL,
        country TEXT NULL,
        primary_airport_code TEXT NULL,
        secondary_airport_code TEXT NULL,
        tertiary_airport_code TEXT NULL,
        friend_cities TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
        timezone TEXT NULL,
        max_cost SMALLINT NULL DEFAULT 1000,
        max_time SMALLINT NULL DEFAULT 1000,
        friday_last_class TIME WITHOUT TIME ZONE NULL,
        monday_first_class TIME WITHOUT TIME ZONE NULL,
        CONSTRAINT user_pkey PRIMARY KEY (id),
        CONSTRAINT user_max_cost_check CHECK (max_cost >= 0),
        CONSTRAINT user_max_time_check CHECK (max_time >= 0)
      );
    `);

  })();

  return schemaBootstrapPromise;
}

module.exports = {
  query: (text, params) => pool.query(text, params),
  pool,
  ensureAppSchema,
};
