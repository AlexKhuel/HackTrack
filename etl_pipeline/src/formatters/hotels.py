#!/usr/bin/env python3
"""Format hotel average-price CSV into rows for public.lodging.

Target schema:
  id bigint generated by default as identity not null,
  city text,
  nightly_rate real

Input CSV columns (flexible):
  - Preferred: city_name (or city), average_price
  - Also supported: airport_code (or iata/iata_code/destination_airport), average_price
    when --airport-city-map is supplied or airport code is in built-in defaults.

By default, this script outputs only `city` + `nightly_rate` because `id` is
identity-generated by Postgres. Use --include-id if you want deterministic ids
in output files.
"""

from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

PRICE_RE = re.compile(r"-?\d+(?:,\d{3})*(?:\.\d+)?")

